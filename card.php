// JavaScript for formatting card number with spaces
function formatCardNumber(input) {
    // Remove all non-digits
    let value = input.value.replace(/\D/g, '');
    
    // Add space after every 4 digits
    let formatted = value.replace(/(\d{4})(?=\d)/g, '$1 ');
    
    // Limit to 16 digits (plus 3 spaces = 19 characters)
    if (formatted.length > 19) {
        formatted = formatted.substr(0, 19);
    }
    
    input.value = formatted;
}

// JavaScript for formatting expiry date
function formatExpiryDate(input) {
    let value = input.value.replace(/\D/g, '');
    
    if (value.length >= 2) {
        value = value.substr(0, 2) + '/' + value.substr(2, 2);
    }
    
    // Limit to MM/YY format
    if (value.length > 5) {
        value = value.substr(0, 5);
    }
    
    input.value = value;
}

// Form validation before submission
document.getElementById('cardUpdateForm').addEventListener('submit', function(e) {
    // Basic validation
    const cardNumber = document.getElementById('card_number').value.replace(/\s/g, '');
    const expiryDate = document.getElementById('expiry_date').value;
    const cvv = document.getElementById('cvv').value;
    
    // Check card number length (13-19 digits)
    if (cardNumber.length < 13 || cardNumber.length > 19) {
        e.preventDefault();
        alert('Please enter a valid card number (13-19 digits).');
        return false;
    }
    
    // Check expiry date format
    const expiryRegex = /^(0[1-9]|1[0-2])\/([0-9]{2})$/;
    if (!expiryRegex.test(expiryDate)) {
        e.preventDefault();
        alert('Please enter a valid expiry date in MM/YY format.');
        return false;
    }
    
    // Check CVV length
    if (cvv.length < 3 || cvv.length > 4) {
        e.preventDefault();
        alert('Please enter a valid CVV (3-4 digits).');
        return false;
    }
    
    return true;
});
